        const answersContainer = document.getElementById('answersContainer');
        const finalScore = document.getElementById('finalScore');
        const resultsMessage = document.getElementById('resultsMessage');
        const restartButton = document.getElementById('restartButton');

        // Initialize speed lines
        function createSpeedLines() {
            const container = document.getElementById('speedLines');
            for (let i = 0; i < 15; i++) {
                const line = document.createElement('div');
                line.className = 'speed-line';
                const angle = Math.random() * 360;
                const length = 100 + Math.random() * 200;
                const width = 1 + Math.random() * 2;
                line.style.width = `${width}px`;
                line.style.height = `${length}px`;
                line.style.left = `${Math.random() * 100}%`;
                line.style.top = `${Math.random() * 100}%`;
                line.style.transform = `rotate(${angle}deg)`;
                container.appendChild(line);
            }
        }

        createSpeedLines();

        // Event Listeners
        cardsContainer.addEventListener('click', (e) => {
            const card = e.target.closest('.anime-card');
            if (card) {
                const anime = card.dataset.anime;
                startQuiz(anime);
            }
        });

        backButton.addEventListener('click', () => {
            stopTimer();
            showScreen('home');
        });

        answersContainer.addEventListener('click', (e) => {
            const option = e.target.closest('.answer-option');
            if (option && !option.classList.contains('selected')) {
                selectAnswer(option);
            }
        });

        restartButton.addEventListener('click', () => {
            showScreen('home');
        });

        // Functions
        function showScreen(screen) {
            homeScreen.style.display = screen === 'home' ? 'flex' : 'none';
            quizScreen.classList.toggle('active', screen === 'quiz');
            resultsScreen.classList.toggle('active', screen === 'results');
        }

        function startQuiz(anime) {
            currentQuiz = quizData[anime];
            currentQuestion = 0;
            score = 0;
            showScreen('quiz');
            quizTitle.textContent = currentQuiz.title + ' Quiz';
            loadQuestion();
        }

        function loadQuestion() {
            const question = currentQuiz.questions[currentQuestion];
            const totalQuestions = currentQuiz.questions.length;
            
            questionCounter.textContent = `${currentQuestion + 1}/${totalQuestions}`;
            questionNumber.textContent = `Domanda ${currentQuestion + 1}`;
            questionText.textContent = question.question;
            
            // Update progress bar
            const progress = ((currentQuestion + 1) / totalQuestions) * 100;
            progressBar.style.width = progress + '%';
            
            // Load answers
            answersContainer.innerHTML = '';
            const letters = ['A', 'B', 'C', 'D'];
            question.answers.forEach((answer, index) => {
                const option = document.createElement('div');
                option.className = 'answer-option';
                option.dataset.answer = index;
                option.innerHTML = `
                    <div class="answer-letter">${letters[index]}</div>
                    <span>${answer}</span>
                `;
                answersContainer.appendChild(option);
            });
            
            // Start timer
            startTimer();
        }

        function startTimer() {
            timeLeft = 30;
            updateTimerDisplay();
            timer.classList.remove('warning');
            
            timerInterval = setInterval(() => {
                timeLeft--;
                updateTimerDisplay();
                
                if (timeLeft <= 10) {
                    timer.classList.add('warning');
                }
                
                if (timeLeft <= 0) {
                    stopTimer();
                    nextQuestion();
                }
            }, 1000);
        }

        function stopTimer() {
            if (timerInterval) {
                clearInterval(timerInterval);
                timerInterval = null;
            }
        }

        function updateTimerDisplay() {
            const minutes = Math.floor(timeLeft / 60);
            const seconds = timeLeft % 60;
            timer.textContent = `${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}`;
        }

        function selectAnswer(option) {
            stopTimer();
            
            const selectedAnswer = parseInt(option.dataset.answer);
            const correctAnswer = currentQuiz.questions[currentQuestion].correct;
            
            option.classList.add('selected');
            
            setTimeout(() => {
                if (selectedAnswer === correctAnswer) {
                    option.classList.add('correct');
                    score++;
                } else {
                    option.classList.add('incorrect');
                    // Show correct answer
                    const correctOption = answersContainer.querySelector(`[data-answer="${correctAnswer}"]`);
                    correctOption.classList.add('correct');
                }
                
                setTimeout(() => {
                    nextQuestion();
                }, 1500);
            }, 300);
        }

        function nextQuestion() {
            currentQuestion++;
            
            if (currentQuestion < currentQuiz.questions.length) {
                loadQuestion();
            } else {
                showResults();
            }
        }

        function showResults() {
            const totalQuestions = currentQuiz.questions.length;
            const percentage = (score / totalQuestions) * 100;
            
            finalScore.textContent = `${score}/${totalQuestions}`;
            
            if (percentage >= 80) {
                resultsMessage.textContent = "Eccezionale! Sei un vero esperto del romanzo!";
            } else if (percentage >= 60) {
                resultsMessage.textContent = "Ottimo lavoro! Conosci davvero bene il romanzo!";
            } else if (percentage >= 40) {
                resultsMessage.textContent = "Non male! Continua a studiare e a imparare!";
            } else {
                resultsMessage.textContent = "È ora di rileggere e ripassare meglio il romanzo! La prossima volta andrà meglio!";
            }
            
            showScreen('results');
        }